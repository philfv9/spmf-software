	/**
	 * Enumerates the non-empty subsets of an itemset in order of increasing size
	 * and then lexicographically, which allows a caller to stop as soon as subsets
	 * exceed a given size.
	 */
	private static class ItemsetSubsetEnumerator {

		/**
		 * Items whose subsets are enumerated.
		 */
		private int[] items = new int[0];

		/**
		 * Size of the current subset.
		 */
		private int currentSize = 0;

		/**
		 * Index of each item of the current subset inside items.
		 */
		private int[] positions = new int[8];

		/**
		 * Buffer storing the items of the current subset.
		 */
		private int[] currentItems = new int[8];

		/**
		 * Number of items in the current subset.
		 */
		private int currentCount = 0;

		/**
		 * Resets the enumerator so that it enumerates the subsets of a new itemset.
		 *
		 * @param newItems the itemset whose subsets must be enumerated
		 */
		void reset(int[] newItems) {
			this.items = newItems;
			if (positions.length < newItems.length) {
				positions = new int[Math.max(newItems.length, positions.length * 2)];
			}
			if (currentItems.length < newItems.length) {
				currentItems = new int[Math.max(newItems.length, currentItems.length * 2)];
			}
			currentSize = 0;
			currentCount = 0;
		}

		/**
		 * Moves the enumerator to the next subset of the itemset.
		 *
		 * @return true if a non-empty subset was produced, or false when all of them
		 *         were produced
		 */
		boolean next() {
			int itemCount = items.length;
			if (currentSize == 0) {
				if (itemCount == 0) {
					return false;
				}
				currentSize = 1;
				positions[0] = 0;
				buildCurrentItems();
				return true;
			}

			int slot = currentSize - 1;
			while (slot >= 0) {
				// A slot can advance only while enough items remain to fill the later slots.
				if (positions[slot] < itemCount - (currentSize - slot)) {
					int nextPosition = positions[slot] + 1;
					positions[slot] = nextPosition;
					for (int laterSlot = slot + 1; laterSlot < currentSize; laterSlot++) {
						nextPosition++;
						positions[laterSlot] = nextPosition;
					}
					buildCurrentItems();
					return true;
				}
				slot--;
			}

			currentSize++;
			if (currentSize > itemCount) {
				currentCount = 0;
				return false;
			}
			for (int index = 0; index < currentSize; index++) {
				positions[index] = index;
			}
			buildCurrentItems();
			return true;
		}

		/**
		 * Fills the current subset buffer from the current item positions.
		 */
		private void buildCurrentItems() {
			if (currentItems.length < currentSize) {
				currentItems = new int[Math.max(currentSize, currentItems.length * 2)];
			}
			for (int index = 0; index < currentSize; index++) {
				currentItems[index] = items[positions[index]];
			}
			currentCount = currentSize;
		}
	}

	/**
	 * Holds the precomputed information required by the duplication conditions
	 * DCond2 and DCond3 for one position list of one generator.
	 */
	private static class DuplicateConditions {

		/**
		 * For each position, the earlier position lists to test with DCond2.
		 */
		final int[][] condition2Indexes;

		/**
		 * For each position, the earlier position lists to test with DCond3.
		 */
		final int[][] condition3Indexes;

		/**
		 * For each earlier position list, the generator itemset tested by DCond2.
		 */
		final int[][] generatorItemsets;

		/**
		 * For each earlier position list, the difference itemset tested by DCond3.
		 */
		final int[][] differenceItemsets;

		/**
		 * For each earlier position list, the position at which it first differs.
		 */
		final int[] earlierPositions;

		/**
		 * Precomputes the information required by the duplication conditions for one
		 * position list.
		 *
		 * @param positionLists     all the position lists of the generator
		 * @param positionListIndex the index of the current position list
		 * @param positionList      the current position list
		 * @param gamma             the itemsets of the generator
		 * @param sigma             the itemsets of the closed sequence
		 */
		DuplicateConditions(int[][] positionLists, int positionListIndex, int[] positionList, int[][] gamma,
				int[][] sigma) {
			int sequenceSize = sigma.length;
			List<List<Integer>> condition2Buckets = createBuckets(sequenceSize);
			List<List<Integer>> condition3Buckets = createBuckets(sequenceSize);

			generatorItemsets = new int[positionListIndex][];
			differenceItemsets = new int[positionListIndex][];
			earlierPositions = new int[positionListIndex];

			for (int earlierIndex = 0; earlierIndex < positionListIndex; earlierIndex++) {
				int[] earlierList = positionLists[earlierIndex];
				int firstDifferenceIndex = 0;
				while (firstDifferenceIndex < earlierList.length && firstDifferenceIndex < positionList.length
						&& earlierList[firstDifferenceIndex] == positionList[firstDifferenceIndex]) {
					firstDifferenceIndex++;
				}
				if (firstDifferenceIndex >= positionList.length) {
					continue;
				}
				int earlierPosition = earlierList[firstDifferenceIndex];
				earlierPositions[earlierIndex] = earlierPosition;
				generatorItemsets[earlierIndex] = gamma[firstDifferenceIndex];
				differenceItemsets[earlierIndex] = differenceAt(sigma, gamma[firstDifferenceIndex], earlierPosition);

				condition2Buckets.get(earlierPosition).add(earlierIndex);
				condition3Buckets.get(positionList[firstDifferenceIndex]).add(earlierIndex);
			}

			condition2Indexes = toArrays(condition2Buckets);
			condition3Indexes = toArrays(condition3Buckets);
		}

		/**
		 * Computes the items of one closed sequence itemset that are not in a generator
		 * itemset.
		 *
		 * @param sigma    the itemsets of the closed sequence
		 * @param itemset  the generator itemset
		 * @param position the position of the closed sequence
		 * @return the items of sigma at that position that are not in the generator
		 *         itemset
		 */
		private static int[] differenceAt(int[][] sigma, int[] itemset, int position) {
			int[] remaining = new int[sigma[position].length];
			int remainingCount = 0;
			for (int itemIndex = 0; itemIndex < sigma[position].length; itemIndex++) {
				int item = sigma[position][itemIndex];
				if (Arrays.binarySearch(itemset, item) < 0) {
					remaining[remainingCount++] = item;
				}
			}
			return Arrays.copyOf(remaining, remainingCount);
		}

		/**
		 * Creates one empty bucket for each position of the closed sequence.
		 *
		 * @param sequenceSize the number of positions of the closed sequence
		 * @return the list of buckets
		 */
		private static List<List<Integer>> createBuckets(int sequenceSize) {
			List<List<Integer>> buckets = new ArrayList<>(sequenceSize);
			for (int position = 0; position < sequenceSize; position++) {
				buckets.add(new ArrayList<Integer>());
			}
			return buckets;
		}

		/**
		 * Converts a list of buckets into an array of integer arrays.
		 *
		 * @param buckets the buckets to convert
		 * @return the array of buckets, where empty buckets are null
		 */
		private static int[][] toArrays(List<List<Integer>> buckets) {
			int[][] result = new int[buckets.size()][];
			for (int position = 0; position < buckets.size(); position++) {
				List<Integer> bucket = buckets.get(position);
				if (bucket.isEmpty()) {
					continue;
				}
				int[] values = new int[bucket.size()];
				for (int index = 0; index < values.length; index++) {
					values[index] = bucket.get(index);
				}
				result[position] = values;
			}
			return result;
		}
	}

