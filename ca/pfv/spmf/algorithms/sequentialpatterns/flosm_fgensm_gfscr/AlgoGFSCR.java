	/**
	 * Runs the GFS-CR algorithm on a file of frequent closed sequences and a file
	 * of frequent generator sequences, and writes all the generated frequent
	 * sequences to an output file.
	 *
	 * @param closedSequenceFilePath    the path of the input file containing the
	 *                                  frequent closed sequences
	 * @param generatorSequenceFilePath the path of the input file containing the
	 *                                  frequent generator sequences
	 * @param outputFilePath            the path of the output file, or null to only
	 *                                  compute statistics
	 * @throws IOException if an error occurs while reading an input file or writing
	 *                     the output file
	 */
	public void runAlgorithm(String closedSequenceFilePath, String generatorSequenceFilePath, String outputFilePath)
			throws IOException {
		if (outputFilePath != null) {
			writer = new BufferedWriter(new FileWriter(outputFilePath), 1 << 16);
			writer.write("@FILETYPE=\"Frequent sequential patterns\"");
			writer.append(System.lineSeparator());
			writer.write("@SOURCE=\"SPMF SOFTWARE https://philippe-fournier-viger.com/spmf/\"");
			writer.append(System.lineSeparator());
		} else {
			writer = null;
		}

		resetStatistics();
		MemoryLogger.getInstance().reset();
		outputBuffer.setLength(0);

		startTime = System.currentTimeMillis();
		try {
			MemoryLogger.getInstance().checkMemory();
			readClosedSequenceFile(closedSequenceFilePath);
			MemoryLogger.getInstance().checkMemory();
			readGeneratorSequenceFile(generatorSequenceFilePath);
			MemoryLogger.getInstance().checkMemory();
			generateAllFrequentSequences();
		} finally {
			if (writer != null) {
				if (outputBuffer.length() > 0) {
					writer.write(outputBuffer.toString());
					outputBuffer.setLength(0);
				}
				writer.close();
			}
			MemoryLogger.getInstance().checkMemory();
			endTime = System.currentTimeMillis();
		}
	}

	/**
	 * Resets every statistic recorded during a previous execution of the algorithm.
	 */
	private void resetStatistics() {
		patternCount = 0;
		closedSequenceCount = 0;
		generatorSequenceCount = 0;
		supportClassCount = 0;
		pairCount = 0;
		positionListCount = 0;
		prunedByDuplicateConditionCount = 0;
		prunedByClosedConditionCount = 0;
		prunedByGeneratorConditionCount = 0;
		closedSequenceWithoutGeneratorCount = 0;
		emptyGeneratorPresent = false;
		emptyGeneratorSupport = 0;
		outputBuffer.setLength(0);
	}

	/**
	 * Reads the input file containing the frequent closed sequences.
	 *
	 * @param inputFilePath the path of the closed sequence input file
	 * @throws IOException if an error occurs while reading the file
	 */
	private void readClosedSequenceFile(String inputFilePath) throws IOException {
		List<Sequence> sequences = readSequenceFile(inputFilePath);
		int sequenceCount = sequences.size();
		closedSequenceCount = sequenceCount;
		closedSequences = new int[sequenceCount][][];
		closedSequenceSupports = new int[sequenceCount];
		closedSequenceItemCounts = new int[sequenceCount];
		for (int sequenceIndex = 0; sequenceIndex < sequenceCount; sequenceIndex++) {
			Sequence sequence = sequences.get(sequenceIndex);
			closedSequences[sequenceIndex] = sequence.itemsets;
			closedSequenceItemCounts[sequenceIndex] = countItems(sequence.itemsets);
			closedSequenceSupports[sequenceIndex] = sequence.support;
		}
	}

	/**
	 * Reads the input file containing the frequent generator sequences.
	 *
	 * @param inputFilePath the path of the generator sequence input file
	 * @throws IOException if an error occurs while reading the file
	 */
	private void readGeneratorSequenceFile(String inputFilePath) throws IOException {
		List<Sequence> sequences = readSequenceFile(inputFilePath);
		int sequenceCount = sequences.size();
		generatorSequences = new int[sequenceCount][][];
		generatorSequenceSupports = new int[sequenceCount];
		generatorSequenceItemCounts = new int[sequenceCount];
		int storedGenerators = 0;
		for (int sequenceIndex = 0; sequenceIndex < sequenceCount; sequenceIndex++) {
			Sequence sequence = sequences.get(sequenceIndex);
			if (sequence.itemsets.length == 0) {
				emptyGeneratorPresent = true;
				emptyGeneratorSupport = sequence.support;
			} else {
				generatorSequences[storedGenerators] = sequence.itemsets;
				generatorSequenceSupports[storedGenerators] = sequence.support;
				generatorSequenceItemCounts[storedGenerators] = countItems(sequence.itemsets);
				storedGenerators++;
			}
		}
		generatorSequenceCount = storedGenerators;
	}

	/**
	 * Reads an SPMF sequential pattern file and returns the sequences that it
	 * contains together with their support values.
	 *
	 * @param inputFilePath the path of the file to read
	 * @return the sequences of the file, in the order in which they appear
	 * @throws IOException if an error occurs while reading the file
	 */
	private List<Sequence> readSequenceFile(String inputFilePath) throws IOException {
		List<Sequence> sequences = new ArrayList<>();
		try (BufferedReader reader = new BufferedReader(
				new InputStreamReader(new FileInputStream(new File(inputFilePath)), "UTF-8"), INPUT_BUFFER_SIZE)) {
			String line;
			while ((line = reader.readLine()) != null) {
				int supportMarker = line.indexOf("#SUP:");
				if (supportMarker < 0) {
					continue;
				}
				int support = parseSupportValue(line, supportMarker + 5);
				if (support < 0) {
					continue;
				}
				int[][] itemsets = parseItemsets(line, supportMarker, support);
				sequences.add(new Sequence(itemsets, support));
			}
		}
		return sequences;
	}

	/**
	 * Parses the integer support value that follows the "#SUP:" marker of a line.
	 *
	 * @param line  the line to parse
	 * @param start the position of the first character following the marker
	 * @return the parsed support value, or -1 if the line does not contain one
	 */
	private static int parseSupportValue(String line, int start) {
		int position = start;
		int lineLength = line.length();
		while (position < lineLength && (line.charAt(position) == ' ' || line.charAt(position) == '\t')) {
			position++;
		}
		int value = 0;
		boolean hasDigit = false;
		while (position < lineLength) {
			char currentChar = line.charAt(position);
			if (currentChar < '0' || currentChar > '9') {
				break;
			}
			value = value * 10 + (currentChar - '0');
			position++;
			hasDigit = true;
		}
		if (!hasDigit) {
			return -1;
		}
		return value;
	}

	/**
	 * Parses the itemsets of one line of a sequential pattern file.
	 *
	 * @param line         the line to parse
	 * @param patternLimit the position at which the pattern ends on that line
	 * @param support      the support value read on that line
	 * @return the itemsets of the sequence, each sorted in ascending order
	 * @throws IOException if the support value of the line is not positive
	 */
	private static int[][] parseItemsets(String line, int patternLimit, int support) throws IOException {
		if (support <= 0) {
			throw new IOException("The support value of a sequence must be positive: " + line);
		}
		List<int[]> itemsets = new ArrayList<>();
		List<Integer> currentItemset = new ArrayList<>();
		int position = 0;
		while (position < patternLimit) {
			char currentChar = line.charAt(position);
			if (currentChar == ' ' || currentChar == '\t') {
				position++;
				continue;
			}
			boolean negative = false;
			if (currentChar == '-') {
				negative = true;
				position++;
			}
			int value = 0;
			boolean hasDigit = false;
			while (position < patternLimit) {
				char digit = line.charAt(position);
				if (digit < '0' || digit > '9') {
					break;
				}
				value = value * 10 + (digit - '0');
				position++;
				hasDigit = true;
			}
			if (!hasDigit) {
				continue;
			}
			int token = negative ? -value : value;
			if (token == ITEMSET_SEPARATOR || token == SEQUENCE_SEPARATOR) {
				if (!currentItemset.isEmpty()) {
					itemsets.add(toSortedArray(currentItemset));
					currentItemset.clear();
				}
				if (token == SEQUENCE_SEPARATOR) {
					break;
				}
			} else {
				currentItemset.add(token);
			}
		}
		if (!currentItemset.isEmpty()) {
			itemsets.add(toSortedArray(currentItemset));
		}
		return itemsets.toArray(new int[itemsets.size()][]);
	}

	/**
	 * Converts a list of item identifiers into a sorted array without duplicates.
	 *
	 * @param items the list of item identifiers to convert
	 * @return the sorted array of distinct item identifiers
	 */
	private static int[] toSortedArray(List<Integer> items) {
		int[] values = new int[items.size()];
		for (int itemIndex = 0; itemIndex < values.length; itemIndex++) {
			values[itemIndex] = items.get(itemIndex);
		}
		Arrays.sort(values);
		int distinctCount = 0;
		for (int itemIndex = 0; itemIndex < values.length; itemIndex++) {
			if (itemIndex == 0 || values[itemIndex] != values[itemIndex - 1]) {
				values[distinctCount++] = values[itemIndex];
			}
		}
		if (distinctCount != values.length) {
			values = Arrays.copyOf(values, distinctCount);
		}
		return values;
	}

	/**
	 * Generates all frequent sequences from the closed sequences and the generator
	 * sequences that were read from the input files.
	 *
	 * @throws IOException if an error occurs while writing the output file
	 */
	private void generateAllFrequentSequences() throws IOException {
		if (closedSequenceCount == 0) {
			return;
		}

		createGeneratorOrder();
		int[] closedOrder = createClosedSequenceOrder();

		int classStart = 0;
		while (classStart < closedSequenceCount) {
			int classSupport = closedSequenceSupports[closedOrder[classStart]];
			int classEnd = classStart + 1;
			while (classEnd < closedSequenceCount && closedSequenceSupports[closedOrder[classEnd]] == classSupport) {
				classEnd++;
			}
			processSupportClass(closedOrder, classStart, classEnd, classSupport);
			supportClassCount++;
			classStart = classEnd;
		}
	}

	/**
	 * Creates the order in which the closed sequences are processed, grouping the
	 * sequences that have the same support value and sorting each group by
	 * decreasing size.
	 *
	 * @return the identifiers of the closed sequences in their processing order
	 */
	private int[] createClosedSequenceOrder() {
		int closedCount = (int) closedSequenceCount;
		int[] order = new int[closedCount];
		for (int sequenceIndex = 0; sequenceIndex < closedCount; sequenceIndex++) {
			order[sequenceIndex] = sequenceIndex;
		}
		int[] buffer = new int[closedCount];
		mergeSort(order, buffer, 0, closedCount - 1);
		return order;
	}

	/**
	 * Sorts an array of closed sequence identifiers with a stable merge sort using
	 * the processing order of the GFS-CR algorithm.
	 *
	 * @param order  the array of closed sequence identifiers to sort
	 * @param buffer the buffer used to merge the sorted subarrays
	 * @param start  the first index of the range to sort
	 * @param end    the last index of the range to sort
	 */
	private void mergeSort(int[] order, int[] buffer, int start, int end) {
		if (start >= end) {
			return;
		}
		int middle = (start + end) >>> 1;
		mergeSort(order, buffer, start, middle);
		mergeSort(order, buffer, middle + 1, end);
		int leftIndex = start;
		int rightIndex = middle + 1;
		int writeIndex = start;
		while (leftIndex <= middle && rightIndex <= end) {
			if (compareClosedSequences(order[leftIndex], order[rightIndex]) <= 0) {
				buffer[writeIndex++] = order[leftIndex++];
			} else {
				buffer[writeIndex++] = order[rightIndex++];
			}
		}
		while (leftIndex <= middle) {
			buffer[writeIndex++] = order[leftIndex++];
		}
		while (rightIndex <= end) {
			buffer[writeIndex++] = order[rightIndex++];
		}
		System.arraycopy(buffer, start, order, start, end - start + 1);
	}

	/**
	 * Compares two closed sequences with the processing order of the GFS-CR
	 * algorithm, sorting them by decreasing support, then decreasing size and then
	 * lexicographically.
	 *
	 * @param firstSequence  the identifier of the first closed sequence
	 * @param secondSequence the identifier of the second closed sequence
	 * @return a value that is negative, zero or positive when the first sequence
	 *         must be processed before, at the same time as, or after the second
	 *         sequence
	 */
	private int compareClosedSequences(int firstSequence, int secondSequence) {
		int firstSupport = closedSequenceSupports[firstSequence];
		int secondSupport = closedSequenceSupports[secondSequence];
		if (firstSupport != secondSupport) {
			return secondSupport - firstSupport;
		}
		int firstItemCount = closedSequenceItemCounts[firstSequence];
		int secondItemCount = closedSequenceItemCounts[secondSequence];
		if (firstItemCount != secondItemCount) {
			return secondItemCount - firstItemCount;
		}
		return compareSequenceItems(closedSequences[firstSequence], closedSequences[secondSequence]);
	}

	/**
	 * Counts the total number of items contained in a sequence.
	 *
	 * @param sequence the sequence whose items are counted
	 * @return the total number of items of the sequence
	 */
	private static int countItems(int[][] sequence) {
		int itemCount = 0;
		for (int itemsetIndex = 0; itemsetIndex < sequence.length; itemsetIndex++) {
			itemCount += sequence[itemsetIndex].length;
		}
		return itemCount;
	}

	/**
	 * Compares the items of two sequences lexicographically.
	 *
	 * @param firstSequence  the first sequence
	 * @param secondSequence the second sequence
	 * @return a value that is negative, zero or positive when the first sequence is
	 *         lexicographically smaller than, equal to, or greater than the second
	 *         sequence
	 */
	private static int compareSequenceItems(int[][] firstSequence, int[][] secondSequence) {
		int position = 0;
		while (position < firstSequence.length && position < secondSequence.length) {
			int[] firstItemset = firstSequence[position];
			int[] secondItemset = secondSequence[position];
			int itemIndex = 0;
			while (itemIndex < firstItemset.length && itemIndex < secondItemset.length) {
				if (firstItemset[itemIndex] != secondItemset[itemIndex]) {
					return firstItemset[itemIndex] - secondItemset[itemIndex];
				}
				itemIndex++;
			}
			if (firstItemset.length != secondItemset.length) {
				return firstItemset.length - secondItemset.length;
			}
			position++;
		}
		return firstSequence.length - secondSequence.length;
	}

	/**
	 * Creates the order in which the generator sequences are scanned when the
	 * generators of a closed sequence are collected, which sorts the generators by
	 * decreasing support value.
	 */
	private void createGeneratorOrder() {
		generatorOrder = new int[(int) generatorSequenceCount];
		for (int generatorIndex = 0; generatorIndex < generatorSequenceCount; generatorIndex++) {
			generatorOrder[generatorIndex] = generatorIndex;
		}
		for (int firstIndex = 1; firstIndex < generatorOrder.length; firstIndex++) {
			int generator = generatorOrder[firstIndex];
			int generatorSupport = generatorSequenceSupports[generator];
			int insertionIndex = firstIndex - 1;
			while (insertionIndex >= 0
					&& generatorSequenceSupports[generatorOrder[insertionIndex]] < generatorSupport) {
				generatorOrder[insertionIndex + 1] = generatorOrder[insertionIndex];
				insertionIndex--;
			}
			generatorOrder[insertionIndex + 1] = generator;
		}
	}

	/**
	 * Processes one support equivalence class, that is, a group of closed sequences
	 * that share the same support value, by generating the frequent sequences of
	 * every pair formed of a closed sequence and one of its generators.
	 *
	 * @param closedOrder  the identifiers of the closed sequences in processing
	 *                     order
	 * @param classStart   the first index of the class inside closedOrder
	 * @param classEnd     the index following the last index of the class
	 * @param classSupport the support shared by the closed sequences of the class
	 * @throws IOException if an error occurs while writing the output file
	 */
	private void processSupportClass(int[] closedOrder, int classStart, int classEnd, int classSupport)
			throws IOException {
		earlierClosedSequenceCount = 0;
		if (earlierClosedSequences.length < classEnd - classStart) {
			earlierClosedSequences = new int[classEnd - classStart][][];
		}

		for (int classIndex = classStart; classIndex < classEnd; classIndex++) {
			int closedSequenceId = closedOrder[classIndex];
			int[][] closedSequence = closedSequences[closedSequenceId];

			collectGeneratorsOf(closedSequence, classSupport);

			if (currentGeneratorCount == 0) {
				closedSequenceWithoutGeneratorCount++;
			} else {
				for (int generatorIndex = 0; generatorIndex < currentGeneratorCount; generatorIndex++) {
					pairCount++;
					generateSubset(closedSequence, closedSequenceSupports[closedSequenceId], currentGenerators,
							generatorIndex);
				}
			}

			earlierClosedSequences[earlierClosedSequenceCount++] = closedSequence;
		}
	}

	/**
	 * Restricts the earlier closed sequences that are tested against a generated
	 * sequence to the ones that contain the generator of the current pair, because
	 * the generated sequence always contains that generator.
	 *
	 * @param generator the generator of the current pair
	 */
	private void collectCandidateClosedSequences(int[][] generator) {
		candidateClosedSequenceCount = 0;
		if (candidateClosedSequences.length < earlierClosedSequenceCount) {
			candidateClosedSequences = new int[Math.max(earlierClosedSequenceCount, 16)][][];
		}
		for (int closedIndex = 0; closedIndex < earlierClosedSequenceCount; closedIndex++) {
			int[][] earlierClosed = earlierClosedSequences[closedIndex];
			if (containsSequence(earlierClosed, generator)) {
				candidateClosedSequences[candidateClosedSequenceCount++] = earlierClosed;
			}
		}
	}

	/**
	 * Collects the generators of a closed sequence, that is, the generator
	 * sequences of the input file that are contained in the closed sequence and
	 * have the same support value, sorted by increasing size.
	 *
	 * @param closedSequence the closed sequence whose generators must be collected
	 * @param classSupport   the support shared by the closed sequence and its
	 *                       generators
	 */
	private void collectGeneratorsOf(int[][] closedSequence, int classSupport) {
		currentGeneratorCount = 0;
		int closedItemCount = countItems(closedSequence);

		for (int orderIndex = 0; orderIndex < generatorOrder.length; orderIndex++) {
			int generatorIndex = generatorOrder[orderIndex];
			if (generatorSequenceSupports[generatorIndex] < classSupport) {
				break;
			}
			if (generatorSequenceSupports[generatorIndex] != classSupport) {
				continue;
			}
			int[][] generator = generatorSequences[generatorIndex];
			if (generatorSequenceItemCounts[generatorIndex] > closedItemCount) {
				continue;
			}
			if (!containsSequence(closedSequence, generator)) {
				continue;
			}
			if (currentGeneratorCount == currentGenerators.length) {
				currentGenerators = Arrays.copyOf(currentGenerators, currentGenerators.length * 2);
			}
			currentGenerators[currentGeneratorCount++] = generator;
		}

		if (emptyGeneratorPresent && emptyGeneratorSupport == classSupport) {
			if (currentGeneratorCount == currentGenerators.length) {
				currentGenerators = Arrays.copyOf(currentGenerators, currentGenerators.length * 2);
			}
			currentGenerators[currentGeneratorCount++] = new int[0][];
		}

		if (currentGeneratorCount > 1) {
			sortGeneratorsBySize();
		}
	}

	/**
	 * Sorts the generators of the current closed sequence by increasing number of
	 * items and then lexicographically, so that short generators are tested first
	 * by the duplication condition of Strategy 2.
	 */
	private void sortGeneratorsBySize() {
		for (int firstIndex = 1; firstIndex < currentGeneratorCount; firstIndex++) {
			int[][] generator = currentGenerators[firstIndex];
			int insertionIndex = firstIndex - 1;
			while (insertionIndex >= 0 && compareGeneratorSize(currentGenerators[insertionIndex], generator) > 0) {
				currentGenerators[insertionIndex + 1] = currentGenerators[insertionIndex];
				insertionIndex--;
			}
			currentGenerators[insertionIndex + 1] = generator;
		}
	}

	/**
	 * Compares two generators by increasing number of items and then
	 * lexicographically.
	 *
	 * @param firstGenerator  the first generator to compare
	 * @param secondGenerator the second generator to compare
	 * @return a value that is negative, zero or positive when the first generator
	 *         must be processed before, at the same time as, or after the second
	 *         generator
	 */
	private static int compareGeneratorSize(int[][] firstGenerator, int[][] secondGenerator) {
		int firstItemCount = countItems(firstGenerator);
		int secondItemCount = countItems(secondGenerator);
		if (firstItemCount != secondItemCount) {
			return firstItemCount - secondItemCount;
		}
		return compareSequenceItems(firstGenerator, secondGenerator);
	}

	/**
	 * Checks whether a sequence contains another sequence as a subsequence.
	 *
	 * @param superSequence the sequence that may contain the other sequence
	 * @param subSequence   the sequence that may be contained
	 * @return true if every itemset of subSequence is a subset of a distinct
	 *         itemset of superSequence in the same order
	 */
	private static boolean containsSequence(int[][] superSequence, int[][] subSequence) {
		int superIndex = 0;
		for (int subIndex = 0; subIndex < subSequence.length; subIndex++) {
			int[] subItemset = subSequence[subIndex];
			boolean matched = false;
			while (superIndex < superSequence.length) {
				int[] superItemset = superSequence[superIndex++];
				if (itemsetContains(superItemset, subItemset)) {
					matched = true;
					break;
				}
			}
			if (!matched) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Checks whether an itemset is a subset of another itemset.
	 *
	 * @param superItemset the itemset that may contain the other itemset
	 * @param subItemset   the itemset that may be contained
	 * @return true if every item of subItemset belongs to superItemset
	 */
	private static boolean itemsetContains(int[] superItemset, int[] subItemset) {
		for (int itemIndex = 0; itemIndex < subItemset.length; itemIndex++) {
			if (Arrays.binarySearch(superItemset, subItemset[itemIndex]) < 0) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Checks whether an itemset given as a prefix of an array is a subset of
	 * another itemset.
	 *
	 * @param subItems     the items of the itemset that may be contained
	 * @param subCount     the number of items of the itemset that may be contained
	 * @param superItemset the itemset that may contain the other itemset
	 * @return true if every item of the given itemset belongs to superItemset
	 */
	private static boolean itemsetContains(int[] subItems, int subCount, int[] superItemset) {
		for (int itemIndex = 0; itemIndex < subCount; itemIndex++) {
			if (Arrays.binarySearch(superItemset, subItems[itemIndex]) < 0) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Checks whether an itemset is a subset of the first items of a sorted buffer.
	 *
	 * @param superItems the sorted buffer whose first items form the containing
	 *                   itemset
	 * @param superCount the number of valid items in the buffer
	 * @param subItemset the sorted itemset that may be contained
	 * @return true if every item of subItemset belongs to the first items of the
	 *         buffer
	 */
	private static boolean prefixContainsItemset(int[] superItems, int superCount, int[] subItemset) {
		for (int itemIndex = 0; itemIndex < subItemset.length; itemIndex++) {
			int item = subItemset[itemIndex];
			int low = 0;
			int high = superCount - 1;
			boolean found = false;
			while (low <= high) {
				int middle = (low + high) >>> 1;
				if (superItems[middle] < item) {
					low = middle + 1;
				} else if (superItems[middle] > item) {
					high = middle - 1;
				} else {
					found = true;
					break;
				}
			}
			if (!found) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Checks whether an itemset given as a prefix of a sorted buffer is a subset of
	 * another itemset.
	 *
	 * @param superItems the sorted buffer whose first items form the containing
	 *                   itemset
	 * @param superCount the number of valid items in the buffer
	 * @param subItems   the sorted buffer whose first items form the contained
	 *                   itemset
	 * @param subCount   the number of valid items of the contained itemset
	 * @return true if every item of the contained itemset belongs to the containing
	 *         itemset
	 */
	private static boolean prefixContainsPrefix(int[] superItems, int superCount, int[] subItems, int subCount) {
		for (int itemIndex = 0; itemIndex < subCount; itemIndex++) {
			int item = subItems[itemIndex];
			int low = 0;
			int high = superCount - 1;
			boolean found = false;
			while (low <= high) {
				int middle = (low + high) >>> 1;
				if (superItems[middle] < item) {
					low = middle + 1;
				} else if (superItems[middle] > item) {
					high = middle - 1;
				} else {
					found = true;
					break;
				}
			}
			if (!found) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Checks whether the sequence being built contains a given sequence, that is,
	 * whether every itemset of the given sequence is a subset of a distinct itemset
	 * of the sequence being built, in the same order.
	 *
	 * @param sequenceItems the per position buffers storing the itemsets of the
	 *                      sequence being built
	 * @param currentCounts the number of items of each itemset of the sequence
	 *                      being built
	 * @param lastPosition  the last position of the sequence being built that was
	 *                      filled
	 * @param target        the sequence that must be contained
	 * @return true if the sequence being built contains the given sequence
	 */
	private static boolean containsSequencePrefix(int[][] sequenceItems, int[] currentCounts, int lastPosition,
			int[][] target) {
		int targetIndex = 0;
		for (int position = 0; position <= lastPosition && targetIndex < target.length; position++) {
			if (currentCounts[position] == 0) {
				continue;
			}
			if (prefixContainsItemset(sequenceItems[position], currentCounts[position], target[targetIndex])) {
				targetIndex++;
			}
		}
		return targetIndex == target.length;
	}

	/**
	 * Checks whether the sequence being built is contained in a given sequence,
	 * that is, whether every non-empty itemset of the sequence being built is a
	 * subset of a distinct itemset of the given sequence, in the same order.
	 *
	 * @param sequenceItems the per position buffers storing the itemsets of the
	 *                      sequence being built
	 * @param currentCounts the number of items of each itemset of the sequence
	 *                      being built
	 * @param lastPosition  the last position of the sequence being built that was
	 *                      filled
	 * @param target        the sequence that may contain the sequence being built
	 * @return true if the sequence being built is contained in the given sequence
	 */
	private static boolean containedInSequence(int[][] sequenceItems, int[] currentCounts, int lastPosition,
			int[][] target) {
		int targetIndex = 0;
		for (int position = 0; position <= lastPosition; position++) {
			if (currentCounts[position] == 0) {
				continue;
			}
			boolean matched = false;
			while (targetIndex < target.length) {
				int[] targetItemset = target[targetIndex++];
				if (prefixContainsPrefix(targetItemset, targetItemset.length, sequenceItems[position],
						currentCounts[position])) {
					matched = true;
					break;
				}
			}
			if (!matched) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Generates the frequent sequences of one pair formed of a closed sequence and
	 * one of its generators, by calling the GFS-OneSubSet procedure of the GFS-CR
	 * algorithm for every position list of the generator.
	 *
	 * @param sigma          the itemsets of the closed sequence
	 * @param support        the support of the closed sequence
	 * @param generators     the generators of the closed sequence in processing
	 *                       order
	 * @param generatorIndex the index of the generator to process
	 * @throws IOException if an error occurs while writing the output file
	 */
	private void generateSubset(int[][] sigma, int support, int[][][] generators, int generatorIndex)
			throws IOException {
		int[][] gamma = generators[generatorIndex];
		collectCandidateClosedSequences(gamma);
		int sequenceSize = sigma.length;

		int[][] positionLists = findPositionLists(sigma, gamma);
		if (positionLists.length == 0) {
			return;
		}

		if (itemsetBuffers == null || itemsetBuffers.length < sequenceSize) {
			itemsetBuffers = new int[sequenceSize][];
			subsetEnumerators = new ItemsetSubsetEnumerator[sequenceSize];
			for (int position = 0; position < sequenceSize; position++) {
				subsetEnumerators[position] = new ItemsetSubsetEnumerator();
			}
		}

		int[][] expanded = new int[sequenceSize][];
		int[][] difference = new int[sequenceSize][];
		int[] currentCounts = new int[sequenceSize];

		for (int positionListIndex = 0; positionListIndex < positionLists.length; positionListIndex++) {
			int[] positionList = positionLists[positionListIndex];
			positionListCount++;

			buildExpandedGenerator(sigma, gamma, positionList, expanded);
			buildDifferenceSequence(sigma, expanded, difference);
			buildRemainingItemBounds(expanded, difference, sequenceSize);

			DuplicateConditions conditions = new DuplicateConditions(positionLists, positionListIndex, positionList,
					gamma, sigma);

			for (int position = 0; position < sequenceSize; position++) {
				currentCounts[position] = 0;
			}
			search(0, sequenceSize, expanded, difference, itemsetBuffers, currentCounts, 0, generators, generatorIndex,
					support, conditions, 0);
		}
	}

	/**
	 * Builds the expanded generator Ex(gamma, lp) of one position list, which has
	 * the same size as the closed sequence.
	 *
	 * @param sigma        the itemsets of the closed sequence
	 * @param gamma        the itemsets of the generator
	 * @param positionList the position list of the generator in the closed sequence
	 * @param expanded     the array receiving the expanded generator
	 */
	private static void buildExpandedGenerator(int[][] sigma, int[][] gamma, int[] positionList, int[][] expanded) {
		for (int position = 0; position < sigma.length; position++) {
			expanded[position] = null;
		}
		for (int generatorIndex = 0; generatorIndex < positionList.length; generatorIndex++) {
			expanded[positionList[generatorIndex]] = gamma[generatorIndex];
		}
	}

	/**
	 * Builds the difference sequence Delta(lp) = sigma minus Ex(gamma, lp).
	 *
	 * @param sigma      the itemsets of the closed sequence
	 * @param expanded   the expanded generator of the position list
	 * @param difference the array receiving the difference sequence
	 */
	private static void buildDifferenceSequence(int[][] sigma, int[][] expanded, int[][] difference) {
		for (int position = 0; position < sigma.length; position++) {
			int[] expandedItemset = expanded[position];
			if (expandedItemset == null) {
				difference[position] = sigma[position];
			} else {
				difference[position] = DuplicateConditions.differenceAt(sigma, expandedItemset, position);
			}
		}
	}

	/**
	 * Computes, for every position of the closed sequence, the smallest and the
	 * largest number of items that a completion starting at that position can add.
	 *
	 * @param expanded     the expanded generator of the current position list
	 * @param difference   the difference sequence of the current position list
	 * @param sequenceSize the number of positions of the closed sequence
	 */
	private void buildRemainingItemBounds(int[][] expanded, int[][] difference, int sequenceSize) {
		if (minimumRemainingItems.length < sequenceSize + 1) {
			minimumRemainingItems = new int[sequenceSize + 1];
			maximumRemainingItems = new int[sequenceSize + 1];
		}
		minimumRemainingItems[sequenceSize] = 0;
		maximumRemainingItems[sequenceSize] = 0;
		for (int position = sequenceSize - 1; position >= 0; position--) {
			int expandedCount = expanded[position] == null ? 0 : expanded[position].length;
			minimumRemainingItems[position] = expandedCount + minimumRemainingItems[position + 1];
			maximumRemainingItems[position] = expandedCount + difference[position].length
					+ maximumRemainingItems[position + 1];
		}
	}

	/**
	 * Finds all the position lists of a generator inside a closed sequence.
	 *
	 * @param sigma the itemsets of the closed sequence
	 * @param gamma the itemsets of the generator
	 * @return the position lists of the generator, sorted in ascending order
	 */
	private static int[][] findPositionLists(int[][] sigma, int[][] gamma) {
		List<int[]> positionLists = new ArrayList<>();
		int[] current = new int[gamma.length];
		enumeratePositionLists(sigma, gamma, 0, 0, current, positionLists);
		int[][] result = new int[positionLists.size()][];
		for (int positionListIndex = 0; positionListIndex < result.length; positionListIndex++) {
			result[positionListIndex] = positionLists.get(positionListIndex);
		}
		return result;
	}

	/**
	 * Recursively enumerates the position lists of a generator inside a closed
	 * sequence.
	 *
	 * @param sigma          the itemsets of the closed sequence
	 * @param gamma          the itemsets of the generator
	 * @param generatorIndex the index of the generator itemset being placed
	 * @param startPosition  the first position of the closed sequence that may be
	 *                       used
	 * @param current        the position list being built
	 * @param positionLists  the list receiving the position lists
	 */
	private static void enumeratePositionLists(int[][] sigma, int[][] gamma, int generatorIndex, int startPosition,
			int[] current, List<int[]> positionLists) {
		if (generatorIndex == gamma.length) {
			positionLists.add(Arrays.copyOf(current, current.length));
			return;
		}
		int[] itemset = gamma[generatorIndex];
		for (int position = startPosition; position < sigma.length; position++) {
			if (itemsetContains(sigma[position], itemset)) {
				current[generatorIndex] = position;
				enumeratePositionLists(sigma, gamma, generatorIndex + 1, position + 1, current, positionLists);
			}
		}
	}

	/**
	 * Performs the SearchFS procedure of the GFS-CR algorithm, which enumerates the
	 * sequences of one position list while applying the duplication conditions of
	 * Strategy 3 and the duplication conditions of Strategies 1 and 2.
	 *
	 * @param position       the position of the closed sequence being filled
	 * @param sequenceSize   the number of positions of the closed sequence
	 * @param expanded       the expanded generator of the current position list
	 * @param difference     the difference sequence of the current position list
	 * @param sequenceItems  the per position buffers storing the itemsets being
	 *                       built
	 * @param currentCounts  the number of items of each itemset of the sequence
	 *                       being built
	 * @param emptyRun       the number of consecutive empty itemsets preceding the
	 *                       current position
	 * @param generators     the generators of the closed sequence in processing
	 *                       order
	 * @param generatorIndex the index of the current generator
	 * @param support        the support of the closed sequence
	 * @param conditions     the precomputed duplication conditions of the position
	 *                       list
	 * @param itemsSoFar     the number of items already added to the sequence being
	 *                       built
	 * @throws IOException if an error occurs while writing the output file
	 */
	private void search(int position, int sequenceSize, int[][] expanded, int[][] difference, int[][] sequenceItems,
			int[] currentCounts, int emptyRun, int[][][] generators, int generatorIndex, int support,
			DuplicateConditions conditions, int itemsSoFar) throws IOException {
		if (position == sequenceSize) {
			emitSequence(sequenceItems, currentCounts, sequenceSize, support);
			return;
		}

		// The recursion is deep and the number of calls is large, so the memory usage
		// is
		// sampled periodically instead of on every call.
		memoryCheckCounter++;
		if (memoryCheckCounter >= MEMORY_CHECK_INTERVAL) {
			memoryCheckCounter = 0;
			MemoryLogger.getInstance().checkMemory();
		}

		boolean pruneByLength = maximumPatternLength != Integer.MAX_VALUE || minimumPatternLength > 1;
		if (pruneByLength) {
			// Every completion adds all remaining expanded items plus at least
			// minimumRemainingItems and at most maximumRemainingItems difference items,
			// which
			// bounds the number of items that the subtree of this position can still reach.
			if (itemsSoFar + minimumRemainingItems[position] > maximumPatternLength) {
				return;
			}
			if (itemsSoFar + maximumRemainingItems[position] < minimumPatternLength) {
				return;
			}
		}

		ItemsetSubsetEnumerator enumerator = subsetEnumerators[position];
		enumerator.reset(difference[position]);
		int[] expandedItemset = expanded[position];
		int[] condition2Indexes = conditions.condition2Indexes[position];
		int[] condition3Indexes = conditions.condition3Indexes[position];

		// The original enumerator produced the empty subset first, and the order
		// matters because
		// a non-empty subset can duplicate a sequence that the empty subset also
		// produces.
		int[] candidateItems = new int[0];
		int candidateCount = 0;
		boolean emptyChoiceExamined = false;
		while (true) {
			if (emptyChoiceExamined) {
				if (!enumerator.next()) {
					break;
				}
				candidateItems = enumerator.currentItems;
				candidateCount = enumerator.currentCount;
				if (pruneByLength
						&& itemsSoFar + candidateCount + minimumRemainingItems[position + 1] > maximumPatternLength) {
					// Subsets are produced in increasing size, so every remaining one is too long.
					break;
				}
			}
			emptyChoiceExamined = true;

			if (isDuplicate(position, emptyRun, expandedItemset, candidateItems, candidateCount, conditions,
					condition2Indexes, condition3Indexes, difference)) {
				prunedByDuplicateConditionCount++;
				continue;
			}

			int[] union = sequenceItems[position];
			if (union == null) {
				union = new int[expandedItemset == null ? candidateCount : expandedItemset.length + candidateCount];
				sequenceItems[position] = union;
			} else if (union.length < (expandedItemset == null ? candidateCount
					: expandedItemset.length + candidateCount)) {
				union = new int[Math.max(
						expandedItemset == null ? candidateCount : expandedItemset.length + candidateCount,
						union.length * 2)];
				sequenceItems[position] = union;
			}
			int unionCount = buildUnion(expandedItemset, candidateItems, candidateCount, union);
			currentCounts[position] = unionCount;

			if (containsEarlierGenerator(sequenceItems, currentCounts, position, generators, generatorIndex)) {
				prunedByGeneratorConditionCount++;
				currentCounts[position] = 0;
				continue;
			}

			int nextEmptyRun = unionCount == 0 ? emptyRun + 1 : 0;
			search(position + 1, sequenceSize, expanded, difference, sequenceItems, currentCounts, nextEmptyRun,
					generators, generatorIndex, support, conditions, itemsSoFar + unionCount);
			currentCounts[position] = 0;
		}
	}

	/**
	 * Checks whether the itemset being placed at one position makes the sequence a
	 * duplicate of a sequence that was generated earlier, according to the
	 * duplication conditions DCond1, DCond2 and DCond3 of Strategy 3.
	 *
	 * @param position          the position of the closed sequence being filled
	 * @param emptyRun          the number of consecutive empty itemsets preceding
	 *                          the position
	 * @param expandedItemset   the itemset of the expanded generator at the
	 *                          position, or null
	 * @param candidateItems    the items of the itemset being placed
	 * @param candidateCount    the number of items of the itemset being placed
	 * @param conditions        the precomputed duplication conditions of the
	 *                          position list
	 * @param condition2Indexes the earlier position lists to test with DCond2 at
	 *                          this position
	 * @param condition3Indexes the earlier position lists to test with DCond3 at
	 *                          this position
	 * @param difference        the difference sequence of the current position list
	 * @return true if the sequence is a duplicate that must not be generated
	 */
	private static boolean isDuplicate(int position, int emptyRun, int[] expandedItemset, int[] candidateItems,
			int candidateCount, DuplicateConditions conditions, int[] condition2Indexes, int[] condition3Indexes,
			int[][] difference) {
		boolean positionInGenerator = expandedItemset != null;

		if (!positionInGenerator && candidateCount > 0 && emptyRun > 0) {
			int firstTestedPosition = position - emptyRun;
			for (int testedPosition = firstTestedPosition; testedPosition < position; testedPosition++) {
				if (itemsetContains(candidateItems, candidateCount, difference[testedPosition])) {
					return true;
				}
			}
		}

		if (condition2Indexes != null) {
			for (int bucketIndex = 0; bucketIndex < condition2Indexes.length; bucketIndex++) {
				int[] generatorItemset = conditions.generatorItemsets[condition2Indexes[bucketIndex]];
				if (prefixContainsPrefix(candidateItems, candidateCount, generatorItemset, generatorItemset.length)) {
					return true;
				}
			}
		}

		if (condition3Indexes != null) {
			for (int bucketIndex = 0; bucketIndex < condition3Indexes.length; bucketIndex++) {
				int earlierIndex = condition3Indexes[bucketIndex];
				int earlierPosition = conditions.earlierPositions[earlierIndex];
				if (emptyRun < position - earlierPosition) {
					continue;
				}
				if (itemsetContains(candidateItems, candidateCount, conditions.differenceItemsets[earlierIndex])) {
					return true;
				}
			}
		}

		return false;
	}

	/**
	 * Stores the union of the expanded generator itemset and a candidate itemset of
	 * one position into the buffer of that position.
	 *
	 * @param expandedItemset the itemset of the expanded generator, or null
	 * @param candidateItems  the items of the candidate itemset
	 * @param candidateCount  the number of items of the candidate itemset
	 * @param union           the buffer receiving the union
	 * @return the number of items of the union
	 */
	private static int buildUnion(int[] expandedItemset, int[] candidateItems, int candidateCount, int[] union) {
		if (expandedItemset == null) {
			System.arraycopy(candidateItems, 0, union, 0, candidateCount);
			return candidateCount;
		}
		int expandedIndex = 0;
		int candidateIndex = 0;
		int writeIndex = 0;
		while (expandedIndex < expandedItemset.length && candidateIndex < candidateCount) {
			if (expandedItemset[expandedIndex] < candidateItems[candidateIndex]) {
				union[writeIndex++] = expandedItemset[expandedIndex++];
			} else {
				union[writeIndex++] = candidateItems[candidateIndex++];
			}
		}
		while (expandedIndex < expandedItemset.length) {
			union[writeIndex++] = expandedItemset[expandedIndex++];
		}
		while (candidateIndex < candidateCount) {
			union[writeIndex++] = candidateItems[candidateIndex++];
		}
		return writeIndex;
	}

	/**
	 * Checks whether the sequence being built already contains one of the
	 * generators that precede the current generator, which implements the
	 * duplication condition DCondG of Strategy 2.
	 *
	 * @param sequenceItems  the per position buffers storing the itemsets of the
	 *                       sequence
	 * @param currentCounts  the number of items of each itemset of the sequence
	 * @param lastPosition   the last position of the sequence that was filled
	 * @param generators     the generators of the closed sequence in processing
	 *                       order
	 * @param generatorIndex the index of the current generator
	 * @return true if the sequence contains an earlier generator
	 */
	private static boolean containsEarlierGenerator(int[][] sequenceItems, int[] currentCounts, int lastPosition,
			int[][][] generators, int generatorIndex) {
		for (int earlierIndex = 0; earlierIndex < generatorIndex; earlierIndex++) {
			int[][] earlierGenerator = generators[earlierIndex];
			if (earlierGenerator.length == 0) {
				continue;
			}
			if (containsSequencePrefix(sequenceItems, currentCounts, lastPosition, earlierGenerator)) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Writes one generated frequent sequence to the output, after eliminating it
	 * when it is contained in a closed sequence that was processed before its own
	 * closed sequence, as required by the duplication condition DCondC of Strategy
	 * 1.
	 *
	 * @param sequenceItems the per position buffers storing the itemsets of the
	 *                      sequence
	 * @param currentCounts the number of items of each itemset of the sequence
	 * @param sequenceSize  the number of positions of the sequence
	 * @param support       the support of the sequence
	 * @throws IOException if an error occurs while writing the output file
	 */
	private void emitSequence(int[][] sequenceItems, int[] currentCounts, int sequenceSize, int support)
			throws IOException {
		int itemCount = 0;
		for (int position = 0; position < sequenceSize; position++) {
			itemCount += currentCounts[position];
		}
		if (itemCount == 0) {
			return;
		}

		for (int closedIndex = 0; closedIndex < candidateClosedSequenceCount; closedIndex++) {
			if (containedInSequence(sequenceItems, currentCounts, sequenceSize - 1,
					candidateClosedSequences[closedIndex])) {
				prunedByClosedConditionCount++;
				return;
			}
		}

		if (itemCount < minimumPatternLength || itemCount > maximumPatternLength) {
			return;
		}

		patternCount++;
		if (writer == null) {
			return;
		}

		patternStringBuilder.setLength(0);
		for (int position = 0; position < sequenceSize; position++) {
			if (currentCounts[position] == 0) {
				continue;
			}
			for (int itemIndex = 0; itemIndex < currentCounts[position]; itemIndex++) {
				patternStringBuilder.append(sequenceItems[position][itemIndex]).append(' ');
			}
			patternStringBuilder.append("-1 ");
		}
		patternStringBuilder.append("#SUP: ").append(support);
		outputBuffer.append(patternStringBuilder).append('\n');

		if (outputBuffer.length() >= OUTPUT_BUFFER_FLUSH_THRESHOLD) {
			writer.write(outputBuffer.toString());
			outputBuffer.setLength(0);
		}
	}

