/**
 * This is an implementation of the GFS-CR algorithm for generating all frequent
 * sequences from the two sets of frequent closed sequences and frequent
 * generator sequences, instead of mining them directly from a sequence
 * database. The algorithm and its three pruning strategies are described by
 * Duong et al. in the paper "An Explicit Relationship between Sequential
 * Patterns and their Concise Representations" published in the proceedings of
 * the BDA 2019 international conference. See the paper for more details about
 * the algorithm.
 *
 * <p>
 * GFS-CR takes two files as input: a file containing the frequent closed
 * sequences of a database and a file containing the frequent generator
 * sequences of the same database, both obtained with the same minimum support
 * threshold. Such files can be produced by the algorithms AlgoFCloSM,
 * AlgoFGENSM, AlgoCMClaSP_bitset and AlgoVGEN from SPMF. Each generated
 * sequence is written to the output file with its support value, using the SPMF
 * format.
 *
 * @author Philippe Fournier-Viger
 */
